    public function run(): void
    {
        $manufacturers = Manufacturer::factory()->count(12)->create();

        $categories = collect();

        foreach (self::CATEGORY_TREE as $parentName => $children) {
            $parent = Category::factory()->create([
                'name' => $parentName,
                'is_active' => true,
            ]);

            $categories->push($parent);

            foreach ($children as $childName) {
                $child = Category::factory()->create([
                    'name' => $childName,
                    'parent_id' => $parent->id,
                    'is_active' => true,
                ]);

                $categories->push($child);
            }
        }

        // Товары раскладываем только по листовым (дочерним) категориям —
        // в родительских категориях-разделах их не заводим.
        foreach (self::CATALOG as $leafName => $cultures) {
            $category = $categories->first(
                fn (Category $category) => $category->name === $leafName && $category->parent_id !== null
            );

            $options = self::CATEGORY_OPTIONS[$leafName];

            foreach ($cultures as $culture => $names) {
                foreach ($names as $name) {
                    $this->createProduct($category, $name, $culture, $options, $manufacturers);
                }
            }
        }

        // Небольшая доля черновиков и архивных — чтобы фильтры в админке было
        // на чём проверять. Имена берём из EXTRA_NAMES тех же подкатегорий,
        // чтобы черновики тоже соответствовали своей культуре.
        $this->seedDraftsAndArchived($categories, $manufacturers);

        $this->seedFilters();
        $this->seedVariants();
        $this->seedRatings();
    }

    /**
     * Черновики (20) и архивные товары (10) — по реалистичным названиям
     * из EXTRA_NAMES, каждый в своей подкатегории, без изображений
     * и флагов витрины (черновик без фото остаётся удаляемым в админке).
     */
    private function seedDraftsAndArchived(Collection $categories, Collection $manufacturers): void
    {
        $leafCategories = $categories->filter(fn (Category $category) => $category->parent_id !== null);

        $pool = collect(self::EXTRA_NAMES)
            ->flatMap(fn (array $cultures, string $leaf) => collect($cultures)->flatMap(
                fn (array $names, string $culture) => collect($names)->map(
                    fn (string $name) => ['leaf' => $leaf, 'culture' => $culture, 'name' => $name]
                )
            ))
            ->shuffle();

        $specs = [
            ['status' => ProductStatus::Draft, 'count' => 20],
            ['status' => ProductStatus::Archived, 'count' => 10],
        ];

        foreach ($specs as $spec) {
            for ($i = 0; $i < $spec['count']; $i++) {
                $entry = $pool->pop() ?? $pool->random();

                $category = $leafCategories->first(
                    fn (Category $category) => $category->name === $entry['leaf']
                );

                $this->createProduct(
                    $category,
                    $entry['name'],
                    $entry['culture'],
                    self::CATEGORY_OPTIONS[$entry['leaf']],
                    $manufacturers,
                    $spec['status'],
                );
            }
        }
    }

    /**
     * Создать один товар. Для опубликованных — изображения и флаги витрины;
     * черновики/архивные создаются без них.
     *
     * @param  array{price: array{int, int}, places: array<int, GrowingPlace>, ripening: array<int, RipeningPeriod>, seed_count: array{int, int}|null, is_seed: bool}  $options
     */
    private function createProduct(
        Category $category,
        string $name,
        ?string $culture,
        array $options,
        Collection $manufacturers,
        ProductStatus $status = ProductStatus::Published,
    ): void {
        $product = Product::factory()->create([
            'status' => $status,
            'category_id' => $category->id,
            'manufacturer_id' => random_int(0, 4) === 0 ? null : $manufacturers->random()->id,
            'name' => $name,
            'culture' => $options['is_seed'] ? $culture : null,
            'price' => random_int($options['price'][0], $options['price'][1]),
            'in_stock' => random_int(1, 100) <= 85,
            'ripening' => $this->randomFrom($options['ripening']),
            'growing_place' => $this->randomFrom($options['places']),
            'is_hybrid' => $options['is_seed'] ? str_contains($name, 'F1') : null,
            'seed_count' => $options['seed_count'] !== null
                ? random_int($options['seed_count'][0], $options['seed_count'][1])
                : null,
        ]);

        if ($status !== ProductStatus::Published) {
            return;
        }

        $imagesCount = random_int(1, 4);

        for ($i = 0; $i < $imagesCount; $i++) {
            ProductImage::factory()->create([
                'product_id' => $product->id,
                'sort_order' => $i,
                'is_main' => $i === 0,
            ]);
        }

        // ~15% товаров попадают в "Хиты продаж" и ~15% в "Рекомендуем"
        // (для витрины на этом этапе — без реальной статистики продаж).
        $product->forceFill([
            'is_bestseller' => random_int(1, 100) <= 15,
            'is_recommended' => random_int(1, 100) <= 15,
        ])->saveQuietly();
    }

    /**
     * Случайный элемент массива либо null для пустого массива.
     *
     * @template T of object|string
     *
     * @param  array<int, T>  $items
     * @return T|null
     */
    private function randomFrom(array $items): object|string|null
    {
        return $items === [] ? null : $items[array_rand($items)];
    }

    /**
     * Группы фильтров на корневые категории + назначение значений товарам
     * по их полям (ripening / growing_place / is_hybrid).
     */
    private function seedFilters(): void
    {
        $definitions = [
            'Овощи' => [
                'Срок созревания' => ['Ранние' => 'early', 'Средние' => 'mid', 'Поздние' => 'late'],
                'Место выращивания' => ['Открытый грунт' => 'open_ground', 'Теплица' => 'greenhouse', 'Универсальное' => 'universal'],
                'Гибрид' => ['Да (F1)' => 'yes', 'Нет' => 'no'],
            ],
            'Зелень и пряности' => [
                'Срок созревания' => ['Ранние' => 'early', 'Средние' => 'mid', 'Поздние' => 'late'],
            ],
            'Цветы' => [
                'Период цветения' => ['Лето' => 'summer', 'Весь сезон' => 'all_season'],
            ],
        ];

        foreach ($definitions as $rootName => $groups) {
            $root = Category::whereNull('parent_id')->where('name', $rootName)->first();

            if ($root === null) {
                continue;
            }

            foreach ($groups as $groupName => $values) {
                $group = FilterGroup::create([
                    'category_id' => $root->id,
                    'name' => $groupName,
                    'slug' => Str::slug($groupName),
                    'sort_order' => 0,
                ]);

                foreach ($values as $valueName => $key) {
                    $filterValue = FilterValue::create([
                        'filter_group_id' => $group->id,
                        'value' => $valueName,
                        'slug' => Str::slug($valueName),
                        'sort_order' => 0,
                    ]);

                    // Назначаем товарам, у которых соответствующее поле заполнено.
                    $products = match ($groupName) {
                        'Срок созревания' => Product::whereNotNull('ripening')
                            ->where('ripening', $key)
                            ->whereIn('category_id', $root->selfAndChildrenIds()),
                        'Место выращивания' => Product::whereNotNull('growing_place')
                            ->where('growing_place', $key)
                            ->whereIn('category_id', $root->selfAndChildrenIds()),
                        'Гибрид' => Product::whereNotNull('is_hybrid')
                            ->where('is_hybrid', $key === 'yes')
                            ->whereIn('category_id', $root->selfAndChildrenIds()),
                        'Период цветения' => Product::whereIn('category_id', $root->selfAndChildrenIds())
                            ->inRandomOrder()->take(40),
                        default => null,
                    };

                    $products?->each(
                        fn (Product $product) => $product->filterValues()->syncWithoutDetaching([$filterValue->id])
                    );
                }
            }
        }
    }

    /**
     * Варианты товара: ~30 товаров получают 2–3 варианта («10/20/50 семян»).
     * Цены вариантов выше основной — основная остаётся "ценой от".
     */
    private function seedVariants(): void
    {
        Product::query()
            ->where('status', ProductStatus::Published)
            ->whereNotNull('culture')
            ->inRandomOrder()
            ->take(29)
            ->each(function (Product $product) {
                $base = $product->price;

                $variants = [
                    ['label' => '10 семян', 'price' => $base, 'in_stock' => true],
                    ['label' => '20 семян', 'price' => (int) ($base * 1.6), 'in_stock' => random_int(1, 100) <= 80],
                    ['label' => '50 семян', 'price' => (int) ($base * 2.5), 'in_stock' => random_int(1, 100) <= 80],
                ];

                foreach ($variants as $i => $variant) {
                    $product->variants()->create([
                        'label' => $variant['label'],
                        'price' => $variant['price'],
                        'in_stock' => $variant['in_stock'],
                        'sort_order' => $i,
                    ]);
                }
            });
    }

    /**
     * Тестовые рейтинги (~60 товаров) — задел под этап отзывов.
     */
    private function seedRatings(): void
    {
        Product::query()
            ->where('status', ProductStatus::Published)
            ->inRandomOrder()
            ->take(58)
            ->each(function (Product $product) {
                $product->forceFill(['rating' => round(random_int(35, 50) / 10, 1)])->saveQuietly();
            });
    }
